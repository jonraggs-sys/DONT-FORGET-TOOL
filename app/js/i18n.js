export const SUPPORTED = Object.keys(STRINGS);

export function detectLang() {
  const saved = safeGet('dft.lang');
  if (saved && STRINGS[saved]) return saved;
  const prefs = navigator.languages || [navigator.language || 'en'];
  for (const p of prefs) {
    const code = String(p).slice(0, 2).toLowerCase();
    if (STRINGS[code]) return code;
  }
  return 'en';
}

export function setLang(code) {
  if (!STRINGS[code]) return;
  try { localStorage.setItem('dft.lang', code); } catch { /* private mode */ }
}

export function pack(code) {
  return STRINGS[code] || STRINGS.en;
}

/** Fill {placeholders} in a template string. */
export function fill(tpl, vars = {}) {
  return String(tpl).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

function safeGet(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}
